"""逐行验证候选证明链（每行 LHS==RHS 数值检查，FAIL 报行）。
群：a=(1 2 3 4 5)(6), b=(1 2 4 5 3 6)。
"""
import itertools

def comp(p, q):
    return tuple(p[q[i] - 1] for i in range(len(p)))

def mulp(*ps):
    r = tuple(range(1, 7))
    for p in ps:
        r = comp(p, r)
    return r

def powp(p, k):
    r = tuple(range(1, 7))
    for _ in range(k % 60):
        r = comp(p, r)
    return r

A = (2, 3, 4, 5, 1, 6)
ONE = tuple(range(1, 7))
B = None
for cand in itertools.permutations(range(1, 7)):
    if cand != ONE and powp(cand, 3) == ONE and powp(mulp(powp(A, 2), cand), 2) == ONE:
        B = cand
        break

def W(*factors):
    """factors: 交替 ('a',k) 元组序列 → 群元素"""
    r = ONE
    for c, k in factors:
        r = mulp(r, powp(A if c == 'a' else B, k))
    return r

def chk(name, lhs, rhs):
    ok = lhs == rhs
    print(f"{'OK ' if ok else 'FAIL'} {name}")
    return ok


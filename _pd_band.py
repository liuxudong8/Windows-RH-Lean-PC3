import math
K = 4/3
rows = [(40000, 1.16698, 1.24874), (100000, 1.17797, 1.25494), (200000, 1.18615, 1.26039),
        (400000, 1.19380, 1.26527), (800000, 1.19746, 1.26638)]
D3 = 1.31392   # 全表逐点 δ, T=8e5
print("PART J  判据：定理自带误差项 O(1/sqrt(logT))，带给 A 的带宽 ±(1/sqrt(logT))/3")
print(f"{'T':>8} {'log(T/2pi)':>11} {'1/sqrtlog':>10} {'带下界':>9} {'带上界':>9} {'D1':>8} {'D1判':>8} {'D2':>8} {'D2判':>8}")
for T, d1, d2 in rows:
    L = math.log(T / (2 * math.pi)); e = 1 / math.sqrt(L)
    lo = K - e / 3; hi = K + e / 3
    j1 = "出界" if d1 < lo else ("界内" if d1 <= hi else "出界")
    j2 = "出界" if d2 < lo else ("界内" if d2 <= hi else "出界")
    print(f"{T:8d} {L:11.4f} {e:10.4f} {lo:9.4f} {hi:9.4f} {d1:8.4f} {j1:>8} {d2:8.4f} {j2:>8}")
L = math.log(800000/(2*math.pi)); e = 1/math.sqrt(L)
print(f"\nT=8e5 逐点 δ (D3) = {D3:.4f}   带 = [{K-e/3:.4f}, {K+e/3:.4f}]  -> ", "界内" if K-e/3 <= D3 <= K+e/3 else "出界")
print(f"\n加权式 5/4 同判：带 = [{1.25-e/4:.4f}, {1.25+e/4:.4f}]   D3 加权值 1.23391")
print(f"  -> ", "界内" if 1.25-e/4 <= 1.23391 <= 1.25+e/4 else "出界")
print("\n【关键】误差带宽 T=8e5 时约 +-9.7%（去权）/ +-7.3%（加权）")
print("  4/3 精确‘复现’在有限 T 上不可能达到；只能落带内。D1 出界 => logT/2pi 是非法刻度。")
